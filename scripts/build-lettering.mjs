/**
 * Compiles the hand-authored lettering in lettering/languages into the files the
 * welcome animation loads:
 *
 *   public/handwriting/<id>.json   strokes (SVG centre-line paths), lengths, timing
 *   data/greetings.json            the sequence and its language metadata
 *
 *   npm run lettering
 */
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compileLanguage, listLanguages } from "../lettering/index.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(ROOT, "public", "handwriting");

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });

const languages = await listLanguages();
const manifest = [];
for (const def of languages) {
  const art = await compileLanguage(def.id);
  fs.writeFileSync(path.join(OUT, `${art.id}.json`), JSON.stringify(art));
  manifest.push({ id: art.id, text: art.text, language: art.language, lang: art.lang, dir: art.dir, script: art.script });
  const kb = (fs.statSync(path.join(OUT, `${art.id}.json`)).size / 1024).toFixed(1);
  const ink = art.strokes.reduce((a, s) => a + s.length, 0);
  console.log(`${art.id.padEnd(3)} ${art.text.padEnd(10)} ${String(art.strokes.length).padStart(3)} strokes  ink ${Math.round(ink)}u  ${kb} KB`);
}

fs.writeFileSync(
  path.join(ROOT, "data", "greetings.json"),
  JSON.stringify(
    {
      $comment:
        "Generated by `npm run lettering` from lettering/index.mjs and lettering/languages/*. Edit those, not this file.",
      greetings: manifest,
    },
    null,
    2,
  ) + "\n",
);
console.log(`${manifest.length} greetings → public/handwriting, data/greetings.json`);
